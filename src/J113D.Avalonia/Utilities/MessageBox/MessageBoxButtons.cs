namespace J113D.Avalonia.Utilities.MessageBox
{
	/// <summary>
	/// Message box buttons
	/// </summary>
	public enum MessageBoxButtons
	{
		/// <summary>
		/// Provides an "Ok" button
		/// </summary>
		Ok,

		/// <summary>
		/// Provides a "Yes" and a "No" button
		/// </summary>
		YesNo,

		/// <summary>
		/// Provides an "Ok" and a "Cancel" button
		/// </summary>
		OkCancel,

		/// <summary>
		/// Provides an "Ok" and an "Abort" button
		/// </summary>
		OkAbort,

		/// <summary>
		/// Provides a "Yes", a "No" and a "Cancel" button
		/// </summary>
		YesNoCancel,

		/// <summary>
		/// Provides a "Yes", a "No" and an "Abort" button
		/// </summary>
		YesNoAbort
	}
}
